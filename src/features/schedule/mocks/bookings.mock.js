// Get today and generate dates around today for demo
const today = new Date();
const fmt = (d) => d.toISOString().slice(0, 16);
const day = (offset, h, m) => {
  const d = new Date(today);
  d.setDate(d.getDate() + offset);
  d.setHours(h, m, 0, 0);
  return fmt(d);
};
